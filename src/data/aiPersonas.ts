function buildAiProfile(
  id: string,
  name: string,
  age: number,
  gender: Profile['gender'],
  bio: string,
  photoSeed: string,
  interests: string[],
  city: string,
  distanceMiles: number,
): Profile {
  const config = AI_PERSONA_CONFIGS[id];
  return {
    id,
    name,
    age,
    gender,
    bio,
    distanceMiles,
    city,
    photos: [AI_PHOTO(photoSeed)],
    interests,
    isAiPersona: true,
    aiPersonaId: id,
    job: 'Spark AI Persona',
    activeToday: true,
    isNew: true,
    openingMove: config?.openerMessages[0],
    prompts: config
      ? [{ question: 'I\'m an AI practice match', answer: config.tagline }]
      : undefined,
  };
}

