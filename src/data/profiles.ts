export function getProfilesWithinRadius(
  radiusMiles: number,
  excludedIds: Set<string>,
): Profile[] {
  return mockProfiles.filter(
    (p) => !excludedIds.has(p.id) && p.distanceMiles <= radiusMiles,
  );
}
